NO_PIC_GAME = {"АУ"}  # words that are never shown as picture cards
def letter_words(ch):
    if ch in IN_MODE: return IN_MODE[ch]
    lw = [w for w,_,_ in WORDS if w[0]==ch and w not in NO_PIC_GAME]
    if ch in FIRST: lw.remove(FIRST[ch]); lw.insert(0, FIRST[ch])
    return lw[:8]
# sticker word (first) for letters where the WORDS order would pick a word shared with another station
FIRST = {"Р":"РАКЕТА","Б":"БАНАН","Д":"ДОМ","Ч":"ЧЕРЕПАХА"}

# syllable -> tts text (stress mark so single syllables are read as syllables, not abbreviations)
def syl_tts(s):
    v = re.search(r"[аеёиоуыэюя]", s)
    return s if not v else s[:v.start()] + "+" + s[v.start():]

TRANSLIT = dict(zip("абвгдеёжзийклмнопрстуфхцчшщъыьэюя",
 ["a","b","v","g","d","e","yo","zh","z","i","j","k","l","m","n","o","p","r","s","t","u","f","h","c","ch","sh","sch","","y","","ee","yu","ya"]))
def slug(w):
    return "".join(TRANSLIT.get(c, c) for c in w.lower())

