L_EXTRA = {"c": " Как в сл+ове ц+ирк."}
PRAISE = ["p1","p2","p3","p4","p5","p6","p7"]

def build():
    clips = {}  # filename -> tts text
    letters = []
    for ch, lid, name, snd, vow in LETTERS:
        clips[f"l_{lid}"] = f"Это б+уква {name}." + L_EXTRA.get(lid, "")
        clips[f"snd_{lid}"] = snd
        clips[f"find_{lid}"] = f"Найд+и б+укву {name}!"
        if ch in IN_MODE:
            clips[f"where_{lid}"] = f"Где есть б+уква {name}?"
        else:
            clips[f"start_{lid}"] = f"Что начин+ается на {name}?"
        clips[f"name_{lid}"] = f"{name}."
        lw = letter_words(ch)
        assert len(lw) >= 3, ch
        letters.append({"ch": ch, "id": lid, "v": vow, "m": "in" if ch in IN_MODE else "start", "w": [slug(x) for x in lw]})
    words = []
    for w, tts, syl in WORDS:
        s = slug(w)
        clips[f"w_{s}"] = tts
        sy = syl.split("-")
        syl_ids = []
        if len(sy) > 1:
            for x in sy:
                sid = "s_" + slug(x)
                clips.setdefault(sid, syl_tts(x))
                syl_ids.append(slug(x))
        words.append({"w": w, "id": s, "syl": sy, "sid": syl_ids})
    for k, t in PHRASES.items():
        clips[f"ph_{k}"] = t
    return letters, words, clips

if __name__ == "__main__":
    L, W, C = build()
    json.dump({"letters": L, "words": W, "praise": PRAISE}, open("game-data.json", "w"), ensure_ascii=False)
    json.dump(C, open("clips.json", "w"), ensure_ascii=False, indent=0)
